'use client';

import { EyeOff, Play, Target } from 'lucide-react';
import CodeEditor from '@/components/CodeEditor';
import GlowButton from '@/components/GlowButton';
import RichText from '@/components/RichText';
import TestResults from '@/components/TestResults';
import { formatArgs } from '@/lib/primary';

// Shared split-screen used by Step 3 (challenge) and Step 4 (fresh test).
export default function ProblemWorkspace({ problem, code, setCode, onSubmit, busy, submitLabel, submitVariant = 'primary', result, extraActions, kicker }) {
  return (
    <div className="grid gap-5 lg:grid-cols-2">
      <section className="glass flex flex-col gap-5 p-6 animate-fade-up">
        <header>
          <p className="label mb-1">{kicker}</p>
          <h2 className="text-xl font-bold text-slate-900 dark:text-white">{problem.title}</h2>
          <p className="mt-1 text-[11px] text-slate-500">
            Generated by {problem.source === 'gemini' ? 'Gemini (validated in the sandbox)' : 'the curated problem bank'}
          </p>
        </header>
        <RichText text={problem.prompt} className="leading-relaxed text-slate-700 dark:text-slate-300" />
        {problem.focus && (
          <div className="rounded-xl border border-violet-400/30 bg-violet-500/5 p-3 text-sm">
            <p className="label mb-1 flex items-center gap-1.5"><Target size={12} /> Focus question</p>
            {problem.focus}
          </div>
        )}
        {problem.examples.length > 0 && (
          <div>
            <p className="label mb-2">Visible examples</p>
            <div className="space-y-2">
              {problem.examples.map((e, i) => (
                <div key={i} className="rounded-xl border border-slate-200 bg-slate-900/[0.03] px-3 py-2 font-mono text-xs dark:border-white/10 dark:bg-black/30">
                  {problem.fnName}({formatArgs(e.args)}) → <span className="text-cyan-700 dark:text-cyan-300">{JSON.stringify(e.expected)}</span>
                </div>
              ))}
            </div>
          </div>
        )}
        {problem.hiddenCount > 0 && (
          <p className="mt-auto flex items-center gap-2 text-xs text-slate-500">
            <EyeOff size={14} /> {problem.hiddenCount} hidden test{problem.hiddenCount > 1 ? 's' : ''} will run on submit.
          </p>
        )}
      </section>

      <div className="flex flex-col gap-4 animate-fade-up">
        <CodeEditor value={code} onChange={setCode} onRun={onSubmit} height="340px" />
        <div className="flex flex-wrap items-center gap-3">
          <GlowButton icon={Play} variant={submitVariant} loading={busy} onClick={onSubmit}>
            {submitLabel}
          </GlowButton>
          {extraActions}
          <span className="text-[11px] text-slate-500">Ctrl/⌘ + Enter</span>
        </div>
        {result && (
          <div className="glass p-4">
            <p className="mb-3 flex items-center justify-between text-sm font-semibold">
              <span>Results</span>
              <span className={`chip ${result.allPassed ? 'border-emerald-500/40 text-emerald-600' : 'border-rose-500/40 text-rose-600 dark:text-rose-300'}`}>
                {result.passed}/{result.total} passed
              </span>
            </p>
            <TestResults results={result.results} fnName={problem.fnName} />
          </div>
        )}
      </div>
    </div>
  );
}
